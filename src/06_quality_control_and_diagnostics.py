def validate_configuration_and_directories(
    contexts: tuple[
        ThresholdContext,
        ...,
    ],
) -> None:
    """Validate configuration, inputs, and pre-created directories."""

    validate_project_configuration()

    if Path(
        PROJECT_DIR
    ).resolve() != ROOT.resolve():
        raise ValueError(
            "Project-root mismatch.\n"
            f"Script-derived root : {ROOT}\n"
            f"Configured root     : {PROJECT_DIR}"
        )

    if not contexts:
        raise ValueError(
            "No thresholds were selected."
        )

    for context in contexts:
        configured_paths = get_threshold_paths(
            context.threshold_c
        )

        configured_centroid = (
            configured_paths.centroid
        )

        configured_qc = (
            configured_paths.quality_control
        )

        if (
            context.input_csv.parent.resolve()
            != configured_centroid.processed_dir.resolve()
        ):
            raise ValueError(
                "Program 06 input is outside the configured centroid "
                "processed-data directory.\n"
                f"Configured : {configured_centroid.processed_dir}\n"
                f"Selected   : {context.input_csv.parent}"
            )

        if (
            context.output_qc_csv.parent.resolve()
            != configured_qc.processed_dir.resolve()
        ):
            raise ValueError(
                "Program 06 output is outside the configured quality-control "
                "processed-data directory.\n"
                f"Configured : {configured_qc.processed_dir}\n"
                f"Selected   : {context.output_qc_csv.parent}"
            )

        directory_pairs = (
            (
                context.table_dir,
                configured_qc.table_dir,
                "table",
            ),
            (
                context.figure_dir,
                configured_qc.figure_dir,
                "figure",
            ),
            (
                context.report_dir,
                configured_qc.report_dir,
                "report",
            ),
        )

        for selected_directory, configured_directory, label in directory_pairs:
            if (
                selected_directory.resolve()
                != configured_directory.resolve()
            ):
                raise ValueError(
                    f"Program 06 {label} directory differs from the central "
                    "quality-control configuration.\n"
                    f"Configured : {configured_directory}\n"
                    f"Selected   : {selected_directory}"
                )

    required_directories: list[
        Path
    ] = []

    for context in contexts:
        required_directories.extend(
            [
                context.output_qc_csv.parent,
                context.table_dir,
                context.figure_dir,
                context.report_dir,
            ]
        )

    if len(
        contexts
    ) > 1:
        required_directories.extend(
            [
                COMPARISON_TABLE_DIR,
                COMPARISON_FIGURE_DIR,
                COMPARISON_REPORT_DIR,
            ]
        )

    missing_directories = sorted(
        {
            directory
            for directory in required_directories
            if not directory.is_dir()
        },
        key=str,
    )

    if missing_directories:
        raise FileNotFoundError(
            "Required output directories are missing. "
            "Run 00_create_project_structure.py first:\n"
            + "\n".join(
                f"  - {directory}"
                for directory in missing_directories
            )
        )


