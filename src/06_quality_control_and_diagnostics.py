def add_physical_range_flags(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """Add physical-range and internal-consistency QC flags."""

    result = dataframe.copy()

    result["qc_lon_out_of_range"] = (
        result["lon_360"].notna()
        & ~result["lon_360"].between(
            PHYSICAL_LON_360_MIN,
            PHYSICAL_LON_360_MAX,
            inclusive="left",
        )
    )

    result["qc_lat_out_of_range"] = (
        result["lat"].notna()
        & ~result["lat"].between(
            PHYSICAL_LAT_MIN,
            PHYSICAL_LAT_MAX,
            inclusive="both",
        )
    )

    result["qc_area_out_of_range"] = (
        result["area_km2"].notna()
        & (
            (result["area_km2"] < PHYSICAL_AREA_MIN_KM2)
            | (result["area_km2"] > EARTH_SURFACE_AREA_KM2)
        )
    )

    result["qc_mean_sst_out_of_range"] = (
        result["mean_pwp_sst_c"].notna()
        & ~result["mean_pwp_sst_c"].between(
            PHYSICAL_SST_MIN_C,
            PHYSICAL_SST_MAX_C,
            inclusive="both",
        )
    )

    result["qc_max_sst_out_of_range"] = (
        result["max_pwp_sst_c"].notna()
        & ~result["max_pwp_sst_c"].between(
            PHYSICAL_SST_MIN_C,
            PHYSICAL_SST_MAX_C,
            inclusive="both",
        )
    )

    result["qc_mean_below_threshold"] = (
        result["mean_pwp_sst_c"].notna()
        & result["threshold_c"].notna()
        & (
            result["mean_pwp_sst_c"]
            < result["threshold_c"] - 1.0e-8
        )
    )

    result["qc_max_below_mean"] = (
        result["max_pwp_sst_c"].notna()
        & result["mean_pwp_sst_c"].notna()
        & (
            result["max_pwp_sst_c"]
            < result["mean_pwp_sst_c"] - 1.0e-8
        )
    )

    result["qc_cell_count_invalid"] = (
        result["pwp_cell_count"].notna()
        & result["mask_cell_count"].notna()
        & (
            (result["pwp_cell_count"] < 0)
            | (
                result["pwp_cell_count"]
                > result["mask_cell_count"]
            )
        )
    )

    result["qc_valid_ocean_count_invalid"] = (
        result["valid_ocean_cell_count"].notna()
        & result["mask_cell_count"].notna()
        & (
            (result["valid_ocean_cell_count"] < 0)
            | (
                result["valid_ocean_cell_count"]
                > result["mask_cell_count"]
            )
        )
    )

    result["qc_low_coverage"] = (
        result["ocean_data_coverage_pct"].isna()
        | (
            result["ocean_data_coverage_pct"]
            < MINIMUM_EXPECTED_COVERAGE_PCT
        )
    )

    original_flag_upper = (
        result["quality_flag"]
        .astype("string")
        .str.upper()
        .fillna("MISSING")
    )

    # LOW_COVERAGE is reassessed directly in this QC script using the
    # operational threshold appropriate for the legacy-mask/OISST pairing.
    # Other original processing flags still require review.
    result["qc_original_quality_flag"] = ~original_flag_upper.isin(
        [
            "OK",
            "LOW_COVERAGE",
        ]
    )

    lon_180_expected = (
        (
            result["lon_360"] + 180.0
        )
        % 360.0
    ) - 180.0

    result["qc_longitude_convention_mismatch"] = (
        result["lon_360"].notna()
        & result["lon_180"].notna()
        & ~np.isclose(
            result["lon_180"],
            lon_180_expected,
            atol=1.0e-6,
            rtol=0.0,
        )
    )

    result["qc_missing_core_value"] = (
        result[
            [
                "lon_360",
                "lat",
                "area_km2",
            ]
        ]
        .isna()
        .any(axis=1)
    )

    return result


