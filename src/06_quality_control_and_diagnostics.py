def build_threshold_comparison_summary(
    results: dict[
        float,
        pd.DataFrame,
    ],
) -> pd.DataFrame:
    """Build QC statistics across all processed thresholds."""

    records: list[
        dict[str, Any]
    ] = []

    for threshold_c, dataframe in sorted(
        results.items()
    ):
        status_counts = dataframe[
            "qc_status"
        ].value_counts()

        records.append(
            {
                "threshold_c": threshold_c,
                "threshold_folder": threshold_folder_name(
                    threshold_c
                ),
                "records": len(
                    dataframe
                ),
                "start_date": dataframe[
                    "date"
                ].min().strftime(
                    "%Y-%m-%d"
                ),
                "end_date": dataframe[
                    "date"
                ].max().strftime(
                    "%Y-%m-%d"
                ),
                "pass_records": int(
                    status_counts.get(
                        "PASS",
                        0,
                    )
                ),
                "check_records": int(
                    status_counts.get(
                        "CHECK",
                        0,
                    )
                ),
                "fail_records": int(
                    status_counts.get(
                        "FAIL",
                        0,
                    )
                ),
                "check_percentage": float(
                    100.0
                    * status_counts.get(
                        "CHECK",
                        0,
                    )
                    / len(
                        dataframe
                    )
                ),
                "fail_percentage": float(
                    100.0
                    * status_counts.get(
                        "FAIL",
                        0,
                    )
                    / len(
                        dataframe
                    )
                ),
                "minimum_coverage_pct": float(
                    dataframe[
                        "ocean_data_coverage_pct"
                    ].min()
                ),
                "maximum_daily_distance_km": float(
                    dataframe[
                        "centroid_distance_km"
                    ].max()
                ),
                "maximum_absolute_longitude_change_deg": float(
                    dataframe[
                        "delta_lon_deg"
                    ].abs().max()
                ),
                "maximum_absolute_latitude_change_deg": float(
                    dataframe[
                        "delta_lat_deg"
                    ].abs().max()
                ),
                "maximum_absolute_area_fraction_change": float(
                    dataframe[
                        "area_fraction_change"
                    ].abs().max()
                ),
            }
        )

    return pd.DataFrame(
        records
    ).sort_values(
        "threshold_c"
    ).reset_index(
        drop=True
    )


