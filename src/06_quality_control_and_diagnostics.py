# DAILY CHANGE DIAGNOSTICS
# =============================================================================

def add_daily_change_metrics(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """Calculate daily changes and threshold-based diagnostic flags."""

    result = dataframe.copy()

    previous_lon = result["lon_360"].shift(1)
    previous_lat = result["lat"].shift(1)

    result["delta_lon_deg"] = circular_longitude_difference_deg(
        result["lon_360"],
        previous_lon,
    )

    result["delta_lat_deg"] = result["lat"].diff()

    result["centroid_distance_km"] = haversine_distance_km(
        lon1_deg=previous_lon.to_numpy(dtype=np.float64),
        lat1_deg=previous_lat.to_numpy(dtype=np.float64),
        lon2_deg=result["lon_360"].to_numpy(dtype=np.float64),
        lat2_deg=result["lat"].to_numpy(dtype=np.float64),
    )

    result["delta_area_km2"] = result["area_km2"].diff()

    previous_area = result["area_km2"].shift(1)

    result["area_fraction_change"] = (
        result["delta_area_km2"]
        / previous_area
    )

    result.loc[
        previous_area <= 0.0,
        "area_fraction_change",
    ] = np.nan

    result["delta_mean_pwp_sst_c"] = (
        result["mean_pwp_sst_c"].diff()
    )

    adjacent_daily = (
        result["time_step_days"].isna()
        | np.isclose(
            result["time_step_days"],
            1.0,
            atol=1.0e-12,
        )
    )

    result["qc_large_lon_change"] = (
        adjacent_daily
        & result["delta_lon_deg"].abs().gt(
            MAX_DAILY_LON_CHANGE_DEG
        )
    )

    result["qc_large_lat_change"] = (
        adjacent_daily
        & result["delta_lat_deg"].abs().gt(
            MAX_DAILY_LAT_CHANGE_DEG
        )
    )

    result["qc_large_centroid_displacement"] = (
        adjacent_daily
        & result["centroid_distance_km"].gt(
            MAX_DAILY_CENTROID_DISTANCE_KM
        )
    )

    result["qc_large_area_change"] = (
        adjacent_daily
        & result["area_fraction_change"].abs().gt(
            MAX_DAILY_AREA_FRACTION_CHANGE
        )
    )

    result["qc_large_mean_sst_change"] = (
        adjacent_daily
        & result["delta_mean_pwp_sst_c"].abs().gt(
            MAX_DAILY_MEAN_SST_CHANGE_C
        )
    )

    return result


