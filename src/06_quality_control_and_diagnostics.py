def build_composite_flags(
    dataframe: pd.DataFrame,
    duplicate_mask: pd.Series,
) -> pd.DataFrame:
    """Classify each record as PASS, CHECK, or FAIL.

    FAIL flags identify structural, physical, or data-integrity problems.
    CHECK flags identify statistically unusual or rapidly changing but
    potentially valid physical events. No observation is removed.
    """

    result = dataframe.copy()

    result["qc_duplicate_date"] = duplicate_mask.to_numpy(dtype=bool)

    fail_flags = [
        "qc_duplicate_date",
        "qc_non_daily_spacing",
        "qc_lon_out_of_range",
        "qc_lat_out_of_range",
        "qc_area_out_of_range",
        "qc_mean_sst_out_of_range",
        "qc_max_sst_out_of_range",
        "qc_mean_below_threshold",
        "qc_max_below_mean",
        "qc_cell_count_invalid",
        "qc_valid_ocean_count_invalid",
        "qc_low_coverage",
        "qc_original_quality_flag",
        "qc_longitude_convention_mismatch",
        "qc_missing_core_value",
    ]

    check_flags = [
        "qc_large_lon_change",
        "qc_large_lat_change",
        "qc_large_centroid_displacement",
        "qc_large_area_change",
        "qc_large_mean_sst_change",
        "qc_lon_robust_outlier",
        "qc_lat_robust_outlier",
        "qc_area_robust_outlier",
        "qc_mean_sst_robust_outlier",
        "qc_constant_lon_sequence",
        "qc_constant_lat_sequence",
        "qc_constant_area_sequence",
    ]

    all_flags = [
        column
        for column in fail_flags + check_flags
        if column in result.columns
    ]

    result[all_flags] = (
        result[all_flags]
        .fillna(False)
        .astype(bool)
    )

    available_fail_flags = [
        column for column in fail_flags if column in result.columns
    ]
    available_check_flags = [
        column for column in check_flags if column in result.columns
    ]

    result["qc_fail_flag_count"] = (
        result[available_fail_flags].sum(axis=1).astype(int)
        if available_fail_flags
        else 0
    )

    result["qc_check_flag_count"] = (
        result[available_check_flags].sum(axis=1).astype(int)
        if available_check_flags
        else 0
    )

    result["qc_flag_count"] = (
        result["qc_fail_flag_count"]
        + result["qc_check_flag_count"]
    )

    result["qc_status"] = np.select(
        [
            result["qc_fail_flag_count"] > 0,
            result["qc_check_flag_count"] > 0,
        ],
        [
            "FAIL",
            "CHECK",
        ],
        default="PASS",
    )

    result["qc_any_flag"] = result["qc_status"] != "PASS"

    def compile_reasons(row: pd.Series) -> str:
        active_flags = [
            column
            for column in all_flags
            if bool(row[column])
        ]
        return ";".join(active_flags)

    result["qc_reasons"] = result.apply(compile_reasons, axis=1)

    return result


