# CONSTANT-VALUE SEQUENCE DETECTION
# =============================================================================

def constant_sequence_mask(
    series: pd.Series,
    minimum_length: int,
    tolerance: float,
) -> pd.Series:
    """
    Identify observations belonging to unusually long constant sequences.
    """

    values = pd.to_numeric(
        series,
        errors="coerce",
    )

    same_as_previous = (
        values.diff().abs() <= tolerance
    )

    groups = (
        (~same_as_previous)
        .cumsum()
    )

    group_sizes = groups.groupby(
        groups
    ).transform("size")

    return (
        values.notna()
        & group_sizes.ge(minimum_length)
    )


def add_constant_sequence_flags(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """Flag extended constant sequences in major variables."""

    result = dataframe.copy()

    result["qc_constant_lon_sequence"] = (
        constant_sequence_mask(
            result["lon_360"],
            minimum_length=CONSTANT_SEQUENCE_MIN_DAYS,
            tolerance=CONSTANT_TOLERANCE,
        )
    )

    result["qc_constant_lat_sequence"] = (
        constant_sequence_mask(
            result["lat"],
            minimum_length=CONSTANT_SEQUENCE_MIN_DAYS,
            tolerance=CONSTANT_TOLERANCE,
        )
    )

    result["qc_constant_area_sequence"] = (
        constant_sequence_mask(
            result["area_km2"],
            minimum_length=CONSTANT_SEQUENCE_MIN_DAYS,
            tolerance=CONSTANT_TOLERANCE,
        )
    )

    return result


