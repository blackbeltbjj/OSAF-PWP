def circular_longitude_difference_deg(
    current: pd.Series,
    previous: pd.Series,
) -> np.ndarray:
    """
    Calculate signed shortest longitude difference in [-180°, 180°).
    """

    difference = (
        (
            current.to_numpy(dtype=np.float64)
            - previous.to_numpy(dtype=np.float64)
            + 180.0
        )
        % 360.0
    ) - 180.0

    return difference


def haversine_distance_km(
    lon1_deg: np.ndarray,
    lat1_deg: np.ndarray,
    lon2_deg: np.ndarray,
    lat2_deg: np.ndarray,
) -> np.ndarray:
    """
    Calculate great-circle distance using the haversine formula.
    """

    lon1_rad = np.deg2rad(lon1_deg)
    lat1_rad = np.deg2rad(lat1_deg)
    lon2_rad = np.deg2rad(lon2_deg)
    lat2_rad = np.deg2rad(lat2_deg)

    delta_lon = lon2_rad - lon1_rad
    delta_lat = lat2_rad - lat1_rad

    haversine_value = (
        np.sin(delta_lat / 2.0) ** 2
        + np.cos(lat1_rad)
        * np.cos(lat2_rad)
        * np.sin(delta_lon / 2.0) ** 2
    )

    haversine_value = np.clip(
        haversine_value,
        0.0,
        1.0,
    )

    central_angle = 2.0 * np.arcsin(
        np.sqrt(haversine_value)
    )

    return EARTH_RADIUS_KM * central_angle


