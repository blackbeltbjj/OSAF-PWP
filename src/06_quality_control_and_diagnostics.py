def load_input_series() -> pd.DataFrame:
    """Load and validate one threshold-specific daily PWP series."""

    if not INPUT_CSV.is_file():
        raise FileNotFoundError(
            "Input time-series file not found:\n"
            f"{INPUT_CSV}\n\n"
            "Run 05_calculate_pwp_centroid.py for this threshold first."
        )

    dataframe = pd.read_csv(
        INPUT_CSV,
        low_memory=False,
    )

    missing_columns = [
        column
        for column in REQUIRED_COLUMNS
        if column not in dataframe.columns
    ]

    if missing_columns:
        raise ValueError(
            "The input CSV is missing required column(s):\n"
            + "\n".join(
                f"  - {column}"
                for column in missing_columns
            )
        )

    dataframe = dataframe.copy()

    dataframe[
        "date"
    ] = pd.to_datetime(
        dataframe[
            "date"
        ],
        errors="coerce",
    )

    invalid_date_count = int(
        dataframe[
            "date"
        ].isna().sum()
    )

    if invalid_date_count > 0:
        raise ValueError(
            f"The input contains {invalid_date_count:,} invalid dates."
        )

    for column in NUMERIC_COLUMNS:
        dataframe[
            column
        ] = pd.to_numeric(
            dataframe[
                column
            ],
            errors="coerce",
        )

    for column in (
        "quality_flag",
        "threshold_source",
        "source_file",
    ):
        dataframe[
            column
        ] = (
            dataframe[
                column
            ]
            .astype(
                "string"
            )
            .fillna(
                "MISSING"
            )
        )

    dataframe[
        "threshold_fallback_used"
    ] = (
        dataframe[
            "threshold_fallback_used"
        ]
        .astype(
            "string"
        )
        .str.lower()
        .map(
            {
                "true": True,
                "false": False,
                "1": True,
                "0": False,
            }
        )
        .fillna(
            False
        )
        .astype(
            bool
        )
    )

    threshold_values = dataframe[
        "threshold_c"
    ].dropna().unique()

    if threshold_values.size != 1:
        raise ValueError(
            "The input series contains multiple threshold values."
        )

    if not np.isclose(
        float(
            threshold_values[0]
        ),
        ACTIVE_THRESHOLD_C,
        rtol=0.0,
        atol=1.0e-12,
    ):
        raise ValueError(
            "Input threshold differs from the active threshold.\n"
            f"Input  : {float(threshold_values[0]):.6f} °C\n"
            f"Active : {ACTIVE_THRESHOLD_C:.6f} °C"
        )

    dataframe = dataframe.sort_values(
        "date"
    ).reset_index(
        drop=True
    )

    return dataframe


