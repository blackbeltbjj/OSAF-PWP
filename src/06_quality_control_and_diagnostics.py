# ROBUST ROLLING ANOMALY DETECTION
# =============================================================================

def rolling_mad(
    series: pd.Series,
    window: int,
    min_periods: int,
) -> pd.Series:
    """Calculate centred rolling median absolute deviation."""

    rolling_median = series.rolling(
        window=window,
        center=True,
        min_periods=min_periods,
    ).median()

    absolute_deviation = (
        series - rolling_median
    ).abs()

    return absolute_deviation.rolling(
        window=window,
        center=True,
        min_periods=min_periods,
    ).median()


def add_robust_anomaly_flags(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """Add rolling robust-z diagnostics for key variables."""

    result = dataframe.copy()

    variables = {
        "lon": "lon_360",
        "lat": "lat",
        "area": "area_km2",
        "mean_sst": "mean_pwp_sst_c",
    }

    for short_name, column in variables.items():
        rolling_median = result[column].rolling(
            window=ROLLING_WINDOW_DAYS,
            center=True,
            min_periods=ROLLING_MIN_PERIODS,
        ).median()

        median_absolute_deviation = rolling_mad(
            series=result[column],
            window=ROLLING_WINDOW_DAYS,
            min_periods=ROLLING_MIN_PERIODS,
        )

        robust_z = (
            0.67448975
            * (
                result[column]
                - rolling_median
            )
            / median_absolute_deviation
        )

        robust_z = robust_z.replace(
            [np.inf, -np.inf],
            np.nan,
        )

        result[
            f"{short_name}_rolling_median"
        ] = rolling_median

        result[
            f"{short_name}_rolling_mad"
        ] = median_absolute_deviation

        result[
            f"{short_name}_robust_z"
        ] = robust_z

        result[
            f"qc_{short_name}_robust_outlier"
        ] = robust_z.abs().gt(
            ROBUST_Z_THRESHOLD
        )

    return result


