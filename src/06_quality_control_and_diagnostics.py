def identify_duplicate_dates(
    dataframe: pd.DataFrame,
) -> pd.Series:
    """Return a Boolean mask identifying duplicate dates."""

    return dataframe["date"].duplicated(
        keep=False
    )


def identify_missing_calendar_dates(
    dataframe: pd.DataFrame,
) -> pd.DatetimeIndex:
    """Identify missing dates between the first and last observations."""

    if dataframe.empty:
        return pd.DatetimeIndex([])

    complete_range = pd.date_range(
        start=dataframe["date"].min(),
        end=dataframe["date"].max(),
        freq="D",
    )

    return complete_range.difference(
        pd.DatetimeIndex(dataframe["date"])
    )


def add_time_spacing_diagnostics(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """Calculate time spacing between adjacent observations."""

    result = dataframe.copy()

    result["time_step_days"] = (
        result["date"]
        .diff()
        .dt.total_seconds()
        .div(86400.0)
    )

    result["qc_non_daily_spacing"] = (
        result["time_step_days"].notna()
        & ~np.isclose(
            result["time_step_days"],
            1.0,
            atol=1.0e-12,
        )
    )

    return result


